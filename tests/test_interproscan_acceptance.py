"""Tests for InterProScan scientific acceptance assertions (Phase E)."""

from __future__ import annotations

import json
from pathlib import Path

from tools.run_interproscan_real_checks import (
    DEFAULT_BASELINE_PATH,
    EXPECTED_C14,
    EXPECTED_SM,
    EXPECTED_SM_IMPORTED_ORIGINS,
    EXPECTED_SM_MISSING_TRANSLATIONS,
)


def test_expected_acceptance_constants():
    """Verify expected acceptance constants match the checked-in versioned baseline JSON."""
    baseline = json.loads(DEFAULT_BASELINE_PATH.read_text(encoding="utf-8"))
    assert baseline["tool"]["name"] == "enrich-bakta"
    c14_base = baseline["samples"]["C14"]["expected"]
    sm_base = baseline["samples"]["SM"]["expected"]

    assert len(EXPECTED_C14["output_sha256"]) == 64
    assert (
        EXPECTED_C14["output_sha256"] == c14_base["interproscan_only"]["output_sha256"]
    )
    assert EXPECTED_C14["insertions"] == c14_base["interproscan_only"]["insertions"]
    assert (
        EXPECTED_C14["candidate_count"]
        == c14_base["interproscan_only"]["candidate_count"]
    )
    assert (
        EXPECTED_C14["emitted_candidate_count"]
        == c14_base["interproscan_only"]["emitted_candidate_count"]
    )
    assert (
        EXPECTED_C14["context_report_sha256"]
        == c14_base["interproscan_only"]["context_report_sha256"]
    )
    assert (
        EXPECTED_SM["output_sha256"]
        == sm_base["restored_interproscan_only"]["output_sha256"]
    )
    assert (
        EXPECTED_SM["context_report_sha256"]
        == sm_base["restored_interproscan_only"]["context_report_sha256"]
    )
    assert (
        tuple(sm_base["pristine_missing_translations"])
        == EXPECTED_SM_MISSING_TRANSLATIONS
    )
    assert (
        tuple(sm_base["restored_interproscan_only"]["imported_query_ids"])
        == EXPECTED_SM_IMPORTED_ORIGINS
    )


def test_interproscan_acceptance_report_if_present():
    """If acceptance report was generated by real checks, verify all 9 gates passed."""
    report_path = Path(".test-output/interproscan-gates/interproscan-real-checks.json")
    if not report_path.is_file():
        return
    report = json.loads(report_path.read_text(encoding="utf-8"))
    assert len(report) >= 9
    for row in report:
        assert row["status"] == "passed", (
            f"Check {row['label']} failed: {row.get('error')}"
        )
